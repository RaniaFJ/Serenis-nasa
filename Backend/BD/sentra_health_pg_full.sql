CREATE TABLE audit_log (
  id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  occurred_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  event_type       TEXT NOT NULL CHECK (event_type IN (
                     'LOGIN_SUCCESS','LOGIN_FAILURE','LOGOUT','SESSION_EXPIRED','PASSWORD_CHANGE',
                     'ACCESS_DENIED','RATE_LIMITED','APP_ACTION',
                     'INSERT','UPDATE','DELETE',
                     'DDL','SYSTEM')),
  success          BOOLEAN,
  astronaut_id     INT,
  identifier       TEXT CHECK (length(identifier) <= 200),
  db_user          TEXT NOT NULL DEFAULT session_user,
  application_name TEXT DEFAULT current_setting('application_name', true),
  db_client_addr   INET DEFAULT inet_client_addr(),
  client_ip        INET,
  user_agent       TEXT CHECK (length(user_agent) <= 500),
  table_name       TEXT,
  record_id        TEXT,
  old_data         JSONB,
  new_data         JSONB,
  details          JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (pg_column_size(details) < 8192)
);
CREATE INDEX idx_audit_time  ON audit_log (occurred_at DESC);
CREATE INDEX idx_audit_astro ON audit_log (astronaut_id, occurred_at DESC);
CREATE INDEX idx_audit_type  ON audit_log (event_type, occurred_at DESC);
CREATE INDEX idx_audit_ip    ON audit_log (client_ip, occurred_at DESC) WHERE client_ip IS NOT NULL;
CREATE INDEX idx_audit_ident ON audit_log (identifier, occurred_at DESC) WHERE identifier IS NOT NULL;
CREATE INDEX idx_audit_table ON audit_log (table_name, occurred_at DESC) WHERE table_name IS NOT NULL;

CREATE FUNCTION audit_log_block_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit_log is append-only (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';
END $$;
CREATE TRIGGER trg_audit_immutable   BEFORE UPDATE OR DELETE ON audit_log
  FOR EACH ROW EXECUTE FUNCTION audit_log_block_mutation();
CREATE TRIGGER trg_audit_no_truncate BEFORE TRUNCATE ON audit_log
  FOR EACH STATEMENT EXECUTE FUNCTION audit_log_block_mutation();

CREATE FUNCTION safe_inet(t TEXT) RETURNS INET LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN RETURN NULLIF(t, '')::inet; EXCEPTION WHEN others THEN RETURN NULL; END $$;

CREATE FUNCTION safe_int(t TEXT) RETURNS INT LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN RETURN NULLIF(t, '')::int; EXCEPTION WHEN others THEN RETURN NULL; END $$;

CREATE FUNCTION audit_row_change() RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = astro, pg_temp AS $$
DECLARE v_old JSONB; v_new JSONB; v_j JSONB;
BEGIN
  IF TG_OP <> 'INSERT' THEN v_old := to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN v_new := to_jsonb(NEW); END IF;
  v_j := COALESCE(v_new, v_old);
  INSERT INTO audit_log (event_type, success, astronaut_id, client_ip, user_agent,
                         table_name, record_id, old_data, new_data, details)
  VALUES (TG_OP, true,
          safe_int(current_setting('app.astronaut_id', true)),
          safe_inet(current_setting('app.client_ip', true)),
          left(NULLIF(current_setting('app.user_agent', true), ''), 500),
          TG_TABLE_NAME,
          COALESCE(v_j->>'id', concat_ws(':', v_j->>'astronaut_id', v_j->>'achievement_id',
                                              v_j->>'indicator_id', v_j->>'environment_id', v_j->>'hazard_id')),
          v_old, v_new,
          jsonb_build_object('trigger_depth', pg_trigger_depth()));
  RETURN NULL;
END $$;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['astronauts','measurements','alerts','task_completions','astronaut_achievements',
                           'indicators','indicator_env_thresholds','indicator_hazards','recommendations',
                           'tasks','achievements','hazards','body_systems','missions','environments','resources']
  LOOP
    EXECUTE format('CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON astro.%I
                    FOR EACH ROW EXECUTE FUNCTION astro.audit_row_change()', t);
  END LOOP;
END $$;

CREATE FUNCTION log_app_event(
  p_event_type   TEXT,
  p_success      BOOLEAN DEFAULT NULL,
  p_astronaut_id INT     DEFAULT NULL,
  p_identifier   TEXT    DEFAULT NULL,
  p_ip           TEXT    DEFAULT NULL,
  p_user_agent   TEXT    DEFAULT NULL,
  p_details      JSONB   DEFAULT '{}'::jsonb
) RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = astro, pg_temp AS $$
DECLARE v_id BIGINT;
BEGIN
  IF p_event_type NOT IN ('LOGIN_SUCCESS','LOGIN_FAILURE','LOGOUT','SESSION_EXPIRED','PASSWORD_CHANGE',
                          'ACCESS_DENIED','RATE_LIMITED','APP_ACTION') THEN
    RAISE EXCEPTION 'event_type % not allowed from application', p_event_type;
  END IF;
  INSERT INTO audit_log (event_type, success, astronaut_id, identifier, client_ip, user_agent, details)
  VALUES (p_event_type,
          COALESCE(p_success, p_event_type NOT IN ('LOGIN_FAILURE','ACCESS_DENIED','RATE_LIMITED')),
          COALESCE(p_astronaut_id, safe_int(current_setting('app.astronaut_id', true))),
          left(p_identifier, 200),
          COALESCE(safe_inet(p_ip), safe_inet(current_setting('app.client_ip', true))),
          left(p_user_agent, 500),
          CASE WHEN p_details IS NULL THEN '{}'::jsonb
               WHEN pg_column_size(p_details) > 8000 THEN jsonb_build_object('truncated', true)
               ELSE p_details END)
  RETURNING id INTO v_id;
  RETURN v_id;
END $$;

-- Security Detection Views
CREATE VIEW v_sec_bruteforce AS
SELECT 'ip'::text AS kind, client_ip::text AS subject, count(*) AS failures,
       count(DISTINCT identifier) AS spread,
       min(occurred_at) AS first_at, max(occurred_at) AS last_at
FROM audit_log
WHERE event_type = 'LOGIN_FAILURE' AND client_ip IS NOT NULL AND occurred_at > now() - interval '15 minutes'
GROUP BY client_ip HAVING count(*) >= 5
UNION ALL
SELECT 'identifier', identifier, count(*),
       count(DISTINCT client_ip),
       min(occurred_at), max(occurred_at)
FROM audit_log
WHERE event_type = 'LOGIN_FAILURE' AND identifier IS NOT NULL AND occurred_at > now() - interval '15 minutes'
GROUP BY identifier HAVING count(*) >= 5;

CREATE VIEW v_sec_login_anomalies AS
SELECT s.id, s.occurred_at, s.astronaut_id, s.identifier, s.client_ip,
       'success_after_failures'::text AS reason
FROM audit_log s
WHERE s.event_type = 'LOGIN_SUCCESS' AND s.occurred_at > now() - interval '24 hours'
  AND (SELECT count(*) FROM audit_log f
        WHERE f.event_type = 'LOGIN_FAILURE' AND f.identifier = s.identifier
          AND f.occurred_at BETWEEN s.occurred_at - interval '15 minutes' AND s.occurred_at) >= 3
UNION ALL
SELECT max(id), max(occurred_at), astronaut_id, NULL::text, NULL::inet,
       'multiple_ips_' || count(DISTINCT client_ip)
FROM audit_log
WHERE event_type = 'LOGIN_SUCCESS' AND astronaut_id IS NOT NULL AND occurred_at > now() - interval '1 hour'
GROUP BY astronaut_id HAVING count(DISTINCT client_ip) >= 3;

CREATE VIEW v_sec_privileged_changes AS
SELECT id, occurred_at, event_type, db_user, astronaut_id, table_name, record_id, details
FROM audit_log
WHERE occurred_at > now() - interval '24 hours'
  AND ( event_type = 'DDL'
     OR (event_type IN ('UPDATE','DELETE') AND table_name IN ('measurements','task_completions'))
     OR (event_type = 'DELETE' AND table_name = 'alerts')
     OR (event_type IN ('INSERT','UPDATE','DELETE')
         AND table_name IN ('indicators','indicator_env_thresholds','indicator_hazards','recommendations',
                            'tasks','achievements','hazards','body_systems','resources')) );

CREATE VIEW v_sec_burst AS
SELECT date_trunc('minute', occurred_at) AS minute, db_user, astronaut_id, count(*) AS events
FROM audit_log
WHERE occurred_at > now() - interval '1 hour'
  AND event_type IN ('INSERT','UPDATE','DELETE','APP_ACTION','ACCESS_DENIED')
GROUP BY 1, 2, 3 HAVING count(*) >= 60;

CREATE VIEW v_sec_cross_astronaut AS
SELECT id, occurred_at, event_type, db_user, astronaut_id AS session_astronaut,
       COALESCE(new_data, old_data) ->> 'astronaut_id' AS row_astronaut, table_name, record_id
FROM audit_log
WHERE astronaut_id IS NOT NULL
  AND COALESCE(new_data, old_data) ->> 'astronaut_id' IS NOT NULL
  AND astronaut_id::text <> COALESCE(new_data, old_data) ->> 'astronaut_id';

