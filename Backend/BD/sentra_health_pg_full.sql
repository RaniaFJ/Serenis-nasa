CREATE TABLE astronauts (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  age INT CONSTRAINT chk_age CHECK (age BETWEEN 18 AND 100),
  sex TEXT CONSTRAINT chk_sex CHECK (sex IN ('F','M','X')),
  height_cm NUMERIC(5,1) CONSTRAINT chk_height CHECK (height_cm BETWEEN 100 AND 250),
  baseline_weight_kg NUMERIC(5,1) CONSTRAINT chk_weight CHECK (baseline_weight_kg BETWEEN 30 AND 250),
  mission_id INT REFERENCES missions(id),
