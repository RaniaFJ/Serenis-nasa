-- 7a. Plausible measurement validation
CREATE FUNCTION check_measurement_plausible() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE lo NUMERIC; hi NUMERIC; c TEXT;
BEGIN
  SELECT abs_min, abs_max, code INTO lo, hi, c FROM indicators WHERE id = NEW.indicator_id;
  IF NEW.value < lo OR NEW.value > hi THEN
    RAISE EXCEPTION 'Invalid value % for % (plausible range % to %)', NEW.value, c, lo, hi
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_meas_plausible BEFORE INSERT OR UPDATE OF value, indicator_id ON measurements
  FOR EACH ROW EXECUTE FUNCTION check_measurement_plausible();

-- 7b. Server-side XP awarding
CREATE FUNCTION award_xp() RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = astro, pg_temp AS $$
BEGIN
  UPDATE astronauts SET xp = xp + COALESCE((SELECT xp_reward FROM tasks WHERE id = NEW.task_id), 0)
  WHERE id = NEW.astronaut_id;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_award_xp AFTER INSERT ON task_completions
  FOR EACH ROW EXECUTE FUNCTION award_xp();

-- 7c. Automatic Alert Generation
CREATE FUNCTION create_alert_after_measurement() RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = astro, pg_temp AS $$
DECLARE s RECORD; r RECORD;
BEGIN
  SELECT status, direction, name INTO s FROM v_measurement_status WHERE id = NEW.id;
  IF s.status <> 'green' THEN
    SELECT action_text, contact_surgeon INTO r FROM recommendations
     WHERE indicator_id = NEW.indicator_id AND direction = s.direction AND severity = s.status LIMIT 1;
    INSERT INTO alerts (astronaut_id, indicator_id, measurement_id, level, message, escalate_to_flight_surgeon)
    VALUES (NEW.astronaut_id, NEW.indicator_id, NEW.id, s.status,
            s.name || ' ' || NEW.value || ' (' || s.direction || '): ' ||
              COALESCE(r.action_text, 'Out of range. Retest and monitor.'),
            COALESCE(r.contact_surgeon, s.status = 'red'));
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_alert AFTER INSERT ON measurements
  FOR EACH ROW EXECUTE FUNCTION create_alert_after_measurement();

