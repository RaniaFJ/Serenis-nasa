-- =====================================================================
-- 6. VIEWS: COLOR STATUS (Environment-aware & Security Invoker)
-- =====================================================================
CREATE VIEW v_measurement_status WITH (security_invoker = true) AS
SELECT m.id, m.astronaut_id, m.indicator_id, i.code, i.name, m.value, i.unit, m.measured_at,
  CASE WHEN m.value BETWEEN t.nmin AND t.nmax THEN 'green'
       WHEN m.value BETWEEN t.wmin AND t.wmax THEN 'yellow'
       ELSE 'red' END AS status,
  CASE WHEN m.value < t.nmin THEN 'low'
       WHEN m.value > t.nmax THEN 'high' END AS direction
FROM measurements m
JOIN indicators i ON i.id = m.indicator_id
JOIN astronauts a ON a.id = m.astronaut_id
LEFT JOIN missions ms ON ms.id = a.mission_id
LEFT JOIN indicator_env_thresholds e ON e.indicator_id = i.id AND e.environment_id = ms.environment_id
CROSS JOIN LATERAL (SELECT COALESCE(e.normal_min, i.normal_min) AS nmin,
                           COALESCE(e.normal_max, i.normal_max) AS nmax,
                           COALESCE(e.warn_min,   i.warn_min)   AS wmin,
                           COALESCE(e.warn_max,   i.warn_max)   AS wmax) t;

CREATE VIEW v_latest_status WITH (security_invoker = true) AS
SELECT DISTINCT ON (astronaut_id, indicator_id) *
FROM v_measurement_status
ORDER BY astronaut_id, indicator_id, measured_at DESC, id DESC;

