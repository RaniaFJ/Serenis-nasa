CREATE TABLE indicator_env_thresholds (
  indicator_id   INT NOT NULL REFERENCES indicators(id),
  environment_id INT NOT NULL REFERENCES environments(id),
  normal_min NUMERIC NOT NULL, normal_max NUMERIC NOT NULL,
  warn_min   NUMERIC NOT NULL, warn_max   NUMERIC NOT NULL,
  source_note TEXT,
  PRIMARY KEY (indicator_id, environment_id),
  CHECK (warn_min <= normal_min AND normal_min <= normal_max AND normal_max <= warn_max)
