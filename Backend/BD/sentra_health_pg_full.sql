-- DDL Event Triggers (Requires Superuser; gracefully skipped otherwise)
CREATE FUNCTION audit_ddl() RETURNS event_trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = astro, pg_temp AS $$
DECLARE r RECORD;
BEGIN
  FOR r IN SELECT command_tag, object_type, object_identity, schema_name FROM pg_event_trigger_ddl_commands() LOOP
    IF r.schema_name = 'astro' OR r.object_identity LIKE 'astro.%' OR r.command_tag IN ('GRANT','REVOKE') THEN
      INSERT INTO audit_log (event_type, table_name, details)
      VALUES ('DDL', r.object_identity, jsonb_build_object('command', r.command_tag, 'object_type', r.object_type));
    END IF;
  END LOOP;
END $$;

CREATE FUNCTION audit_drop() RETURNS event_trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = astro, pg_temp AS $$
DECLARE r RECORD;
BEGIN
  IF to_regclass('astro.audit_log') IS NULL THEN RETURN; END IF;
  FOR r IN SELECT object_type, object_identity FROM pg_event_trigger_dropped_objects() LOOP
    IF r.object_type IN ('table','view','function','policy','trigger')
       AND (r.object_identity LIKE 'astro.%' OR r.object_identity LIKE '% on astro.%') THEN
      INSERT INTO audit_log (event_type, table_name, details)
      VALUES ('DDL', r.object_identity, jsonb_build_object('command', 'DROP', 'object_type', r.object_type));
    END IF;
  END LOOP;
END $$;

DO $$ BEGIN
  CREATE EVENT TRIGGER trg_astro_audit_ddl  ON ddl_command_end EXECUTE FUNCTION astro.audit_ddl();
  CREATE EVENT TRIGGER trg_astro_audit_drop ON sql_drop        EXECUTE FUNCTION astro.audit_drop();
EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE 'Event triggers need superuser: DDL auditing skipped (use pgaudit instead).';
END $$;

