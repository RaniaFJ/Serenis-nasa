  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  environment_id INT REFERENCES environments(id),
  start_date DATE,
  planned_days INT,
  comm_delay_sec INT DEFAULT 0
